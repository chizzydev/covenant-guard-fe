// Cross-platform end-to-end release provenance verification after P07 proof.
import { readFileSync,existsSync,writeFileSync,mkdirSync } from 'node:fs';
import { resolve,dirname,sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const hash=(p)=>createHash('sha256').update(readFileSync(resolve(root,p))).digest('hex');
const must=(cond,msg)=>{if(!cond)throw Error('P08_PROVENANCE_'+msg)};
const manifest=readFileSync(resolve(root,'MANIFEST_SHA256.txt'),'utf8').trim().split(/\r?\n/);
const seen=new Set();
for(const line of manifest){
  const match=/^([0-9a-fA-F]{64})  ([A-Za-z0-9_.\/-]+)$/.exec(line);
  must(match!==null,'MANIFEST_SYNTAX');
  const rel=match[2];const actualPath=resolve(root,rel);
  must(!seen.has(rel)&&!rel.startsWith('/')&&!rel.includes('\\')&&!rel.split('/').includes('..')&&actualPath.startsWith(root+sep),'MANIFEST_PATH');
  seen.add(rel);must(existsSync(actualPath),'MISSING_'+rel);must(hash(rel)===match[1].toLowerCase(),'HASH_DRIFT_'+rel);
}
console.log(`P08_PACKAGE_FILES_VERIFIED=${manifest.length}`);
const old=readFileSync(resolve(root,'docs/P06_R4_VERIFIED_SOURCE_MANIFEST.txt'),'utf8').trim().split(/\r?\n/);
let oldCount=0;
for(const line of old){
  const match=/^([0-9a-fA-F]{64})  ([A-Za-z0-9_.\/-]+)$/.exec(line);
  must(match!==null,'OLD_MANIFEST_BAD');
  const rel=match[2]==='README.md'?'docs/P06_R4_FROZEN_README.md':match[2]==='RUN_WINDOWS.ps1'?'RUN_BASELINE_WINDOWS.ps1':match[2];
  must(hash(rel)===match[1].toLowerCase(),'FROZEN_P06_SOURCE_DRIFT_'+rel);oldCount++;
}
must(oldCount===68,'FROZEN_P06_COUNT');
console.log('P08_P06_R4_FROZEN_68_FILES=PASS');
for(const consumer of ['allocation_flagship','allocation_pilot','governance_registry']){
  const toml=readFileSync(resolve(root,`consumers/${consumer}/fe.toml`),'utf8');
  must(toml.includes('covenant_transition = { path = "../../library/covenant_transition" }'),'DEPENDENCY_'+consumer);
}
console.log('P08_SAME_INGOT_THREE_CONSUMERS=PASS');
const p07=JSON.parse(readFileSync(resolve(root,'results/p07/P07_RUN_MANIFEST.json'),'utf8'));
const expected={fe:98,baselineNode:45,pythonModelUnit:15,seededTransactions:300,actorSelectorPhaseCases:72,finitePreviewCases:432,compiledMutants:8,killedMutants:8};
for(const [key,n] of Object.entries(expected))must(p07.results?.[key]===n,'P07_COUNT_'+key);
for(const [key,file] of Object.entries({libraryFeSha256:'library/covenant_transition/src/lib.fe',flagshipFeSha256:'consumers/allocation_flagship/src/lib.fe',
  packageLockSha256:'package-lock.json',flagshipBinarySha256:'artifacts/guard/flagship/AllocationFlagship.bin',
  flagshipAbiSha256:'artifacts/guard/flagship/AllocationFlagship.abi.json'})){
  must(p07.source?.[key]===hash(file),'P07_PROVENANCE_'+key);
}
console.log('P08_P07_VERIFIED_COUNTS_AND_ARTIFACT_HASHES=PASS');
const witness=JSON.parse(readFileSync(resolve(root,'results/p08/JUDGE_WITNESS.json'),'utf8'));
must(witness.steps?.length===6&&witness.steps.filter(x=>x.success).length===4&&witness.steps.filter(x=>!x.success).length===2,'WITNESS_STEPS');
must(witness.sourceSha256.library===hash('library/covenant_transition/src/lib.fe')&&
  witness.sourceSha256.flagship===hash('consumers/allocation_flagship/src/lib.fe'),'WITNESS_SOURCE_DRIFT');
const receipt={schema:'COVENANT_GUARD_P08_REPRODUCIBLE_RELEASE_V1',
  timestamp:new Date().toISOString(),platform:process.platform,arch:process.arch,nodeVersion:process.version,
  feVersion:'fe 26.5.0 (3dab95f)',feSha256:process.env.P08_FE_EXE?createHash('sha256').update(readFileSync(process.env.P08_FE_EXE)).digest('hex'):null,
  scope:{sourceFilesVerified:manifest.length,frozenHistoricalFiles:oldCount,independentConsumers:3},
  sourceHashes:{library:hash('library/covenant_transition/src/lib.fe'),flagship:hash('consumers/allocation_flagship/src/lib.fe'),
    packageLock:hash('package-lock.json'),compiledFlagship:hash('artifacts/guard/flagship/AllocationFlagship.bin')},
  p07Results:p07.results,witness:{steps:6,accepted:4,rejected:2},
  notes:['P07 result manifests generated by tests, not checked in','No public chain, production secrets or custodial assets',
  'CI configuration is prepared; not certified as passing until GitHub executes it','Fe binary SHA is platform-specific']};
mkdirSync(resolve(root,'results/p08'),{recursive:true});
writeFileSync(resolve(root,'results/p08/P08_REPRODUCIBILITY_RECEIPT.json'),JSON.stringify(receipt,null,2));
console.log('P08_PROVENANCE_RECEIPT=PASS');
